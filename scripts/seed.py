"""Idempotent deterministic demo content using only locally generated video.

Run inside the compose seed container. DEMO_PASSWORD is generated by deploy.sh.
Existing users retain their password; seed never silently resets credentials.
"""
import os
from pathlib import Path
import subprocess
import tempfile
import time
import urllib.error
import urllib.request
import json
import http.cookiejar
import uuid

from sqlalchemy import select
from app.db import SessionLocal, init_db
from app.models import User
from app.security import hash_password

BASE = os.getenv('SEED_BASE_URL', 'http://app:8000')
PASSWORD = os.getenv('DEMO_PASSWORD')
if not PASSWORD:
    raise SystemExit('DEMO_PASSWORD is required. Use scripts/deploy.sh or set a strong password.')


def client():
    return urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))


def request(opener, method, path, data=None, raw=None, content_type=None):
    headers = {}
    if os.getenv('PUBLIC_ORIGIN'):
        headers['Origin'] = os.environ['PUBLIC_ORIGIN']
    if data is not None:
        raw = json.dumps(data).encode()
        headers['Content-Type'] = 'application/json'
    if content_type:
        headers['Content-Type'] = content_type
    req = urllib.request.Request(BASE + path, data=raw, headers=headers, method=method)
    with opener.open(req, timeout=90) as response:
        payload = response.read()
        return json.loads(payload) if payload else None


def upload(opener, path, title, description, visibility='public'):
    boundary = uuid.uuid4().hex
    chunks = []
    for name, value in {'title': title, 'description': description, 'visibility': visibility}.items():
        chunks.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"\r\n\r\n{value}\r\n'.encode())
    chunks.append(f'--{boundary}\r\nContent-Disposition: form-data; name="file"; filename="demo.mp4"\r\nContent-Type: video/mp4\r\n\r\n'.encode())
    chunks.append(path.read_bytes())
    chunks.append(f'\r\n--{boundary}--\r\n'.encode())
    return request(opener, 'POST', '/api/videos', raw=b''.join(chunks), content_type=f'multipart/form-data; boundary={boundary}')


def make_video(path, color, frequency, index):
    # Synthetic geometric scene plus sound, reproducible and redistributable.
    subprocess.run([
        'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
        '-f', 'lavfi', '-i', f'color=c={color}:s=960x540:r=24:d=8',
        '-f', 'lavfi', '-i', f'sine=frequency={frequency}:sample_rate=44100:duration=8',
        '-vf', f'drawgrid=width=96:height=54:thickness=1:color=white@0.12,drawbox=x={100+index*60}:y=180:w=160:h=160:color=white@0.65:t=fill',
        '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-preset', 'ultrafast',
        '-c:a', 'aac', '-movflags', '+faststart', '-shortest', str(path)
    ], check=True, timeout=90)


def wait_ready(opener, video_id):
    # Bound queue pressure: a low-resource clean VM must not hit pending-job quotas.
    deadline = time.monotonic() + 240
    while time.monotonic() < deadline:
        video = request(opener, 'GET', f'/api/videos/{video_id}')
        if video['status'] == 'ready':
            return video
        if video['status'] == 'failed':
            raise RuntimeError(f'Demo video {video_id} failed processing; inspect worker logs and rerun seed to recreate it')
        time.sleep(2)
    raise RuntimeError(f'Demo video {video_id} processing timed out: inspect docker compose logs worker')


def main():
    init_db()
    accounts = [
        ('creator@demo.local', 'Studio North', 'user'),
        ('viewer@demo.local', 'Alex Morgan', 'user'),
        ('moderator@demo.local', 'Community Moderator', 'moderator'),
        ('admin@demo.local', 'Platform Admin', 'admin'),
    ]
    with SessionLocal() as db:
        for email, display_name, role in accounts:
            if not db.scalar(select(User).where(User.email == email)):
                db.add(User(email=email, display_name=display_name, role=role, password_hash=hash_password(PASSWORD)))
        db.commit()
    creator, viewer = client(), client()
    request(creator, 'POST', '/api/auth/login', {'email': accounts[0][0], 'password': PASSWORD})
    request(viewer, 'POST', '/api/auth/login', {'email': accounts[1][0], 'password': PASSWORD})
    existing = request(creator, 'GET', '/api/videos?mine=true')
    by_title = {v['title']: v for v in existing}
    catalog = [
        ('A quiet morning in the mountains', '0x284b63', 220),
        ('Building something from nothing', '0x5f0f40', 260),
        ('The science of small daily habits', '0x365b37', 300),
        ('Inside a minimalist creative studio', '0x99582a', 340),
        ('A journey beyond the city lights', '0x1b263b', 380),
        ('Designing a better everyday experience', '0x71507a', 420),
        ('Finding your next great idea', '0x00838f', 460),
        ('How music changes the way we think', '0xa4243b', 500),
        ('Private studio preview', '0x4059ad', 540),
    ]
    with tempfile.TemporaryDirectory() as directory:
        for index, (title, color, frequency) in enumerate(catalog):
            previous = by_title.get(title)
            if previous and previous['status'] == 'failed':
                request(creator, 'DELETE', f"/api/videos/{previous['id']}")
                previous = None
            if previous:
                wait_ready(creator, previous['id'])
                if index == 8:
                    request(creator, 'PUT', f"/api/videos/{previous['id']}/access", {'email': accounts[1][0]})
                continue
            path = Path(directory) / f'demo-{index}.mp4'
            make_video(path, color, frequency, index)
            video = upload(creator, path, title, 'Original synthetic demonstration clip. Generated locally with FFmpeg; no external media or third-party copyright assets.', 'private' if index == 8 else 'public')
            wait_ready(creator, video['id'])
            if index == 8:
                request(creator, 'PUT', f"/api/videos/{video['id']}/access", {'email': accounts[1][0]})
    videos = request(creator, 'GET', '/api/videos?mine=true')
    public = [v for v in videos if v['visibility'] == 'public']
    for video in public[:3]:
        request(viewer, 'PUT', f"/api/videos/{video['id']}/like")
        comments = request(viewer, 'GET', f"/api/videos/{video['id']}/comments")
        body = 'Love the attention to detail. Thanks for sharing!'
        if not any(c['body'] == body for c in comments):
            request(viewer, 'POST', f"/api/videos/{video['id']}/comments", {'body': body})
    me = request(creator, 'GET', '/api/auth/me')
    request(viewer, 'PUT', f"/api/users/{me['id']}/subscribe")
    playlists = request(creator, 'GET', f"/api/playlists?channel_id={me['id']}")
    playlist = next((p for p in playlists if p['title'] == 'Start here'), None)
    if not playlist:
        playlist = request(creator, 'POST', '/api/playlists', {'title': 'Start here'})
    for video in public[:4]:
        request(creator, 'PUT', f"/api/playlists/{playlist['id']}/videos/{video['id']}")
    print('Demo is ready. Accounts: ' + ', '.join(a[0] for a in accounts))
    print('Password: use DEMO_PASSWORD from your private .env file.')
    print('viewer@demo.local is explicitly allowed to view the private preview.')


if __name__ == '__main__':
    main()
